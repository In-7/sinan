/// 内容指纹——**判变专用，不是安全用途**。
///
/// 从 `note_store.dart` 抽出来，是为了让**块级判变**（`block_store.dart`）
/// 与整篇判变共用同一份实现：同一个算法、同一个前缀，将来换版本只改一处。
///
/// ## 为什么不用 SHA-256
/// 判变只需要"敏锐地发现不一致"，不需要抗碰撞强度。而原先的
/// `utf8.encode` + `crypto` 包（纯 Dart）SHA-256 是保存热路径上最贵的一步。
/// 本机实测（中英混排的块树 JSON，单位 ms/次）：
///
/// | 长度 | utf8+SHA-256 | 本指纹 | 倍数 |
/// |---|---|---|---|
/// | 10K | 0.116 | 0.009 | ~13x |
/// | 100K | 1.138 | 0.085 | ~13x |
/// | 977K | 11.525 | 0.827 | ~14x |
///
/// 快一个数量级来自三点：① **不产出 utf8 副本**（省掉一次 O(n) 分配 + GC）；
/// ② 逐 code unit 的整数循环取代分组压缩函数；③ 便宜到**可以同步跑**——
/// 977K 字符也只有 0.8ms，远在一帧预算（16.7ms）内，于是不必为它新建 isolate
/// （`Isolate.run` 是一次性的 `Isolate.spawn`，没有池化，每次都要付 2-4MB
/// 堆 + 冷启动）。
///
/// ## ⚠️ 为什么是**全量扫描而不是采样**
/// 采样（只取若干固定位置的片段）必然有**假阴性**：同一长度的替换正好落在
/// 采样区之外时指纹相同，判变会得出"没改"从而跳过落盘——等于**静默丢掉
/// 这一次编辑**。全量扫描是 O(n) 但常数极小（见上表），用实测到的性能冗余
/// 换零假阴性，这笔交换才划算。
///
/// ## 算法
/// FNV-1a 64 位 + splitmix64 收尾：FNV 单独用有"末位弱敏感"的毛病，
/// 收尾变换把它抹平；长度折进种子（长度永远是最强的区分器）。
/// 64 位空间下碰撞概率可忽略（生日界约 2^32 次比较才到 50%，而这里每次保存
/// 只比一次）。
///
/// 返回值形如 `fp1:<长度十六进制>:<指纹十六进制>`（`fp1` = 算法版本）。
/// 老库存的是 SHA-256 十六进制，所以迁移后首次保存必然判"变了"而多写一次
/// ——幂等、无害。
String contentFingerprint(String content) {
  const int mask64 = 0xFFFFFFFFFFFFFFFF;
  final int n = content.length;
  int h = 0xcbf29ce484222325 ^ n;
  for (int i = 0; i < n; i++) {
    h = (h ^ content.codeUnitAt(i)) * 0x100000001b3 & mask64;
  }
  h = (h ^ (h >>> 33)) * 0xff51afd7ed558ccd & mask64;
  h = (h ^ (h >>> 33)) * 0xc4ceb9fe1a85ec53 & mask64;
  h = (h ^ (h >>> 33)) & mask64;
  return 'fp1:${n.toRadixString(16)}:${h.toRadixString(16)}';
}
